export function t(key: keyof typeof dict.tr, lang: Lang): string {
  return dict[lang][key] ?? dict.tr[key];
}

export function tf(
  key: keyof typeof dict.tr,
  lang: Lang,
  vars: Record<string, string | number>,
): string {
  let s = t(key, lang);
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

